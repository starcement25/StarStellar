Star Cement Limited is the leading cement manufacturer in North East India
and is the No. 1 cement brand in the North East. Set up in 2004, the plant
is spread across 200 hectares of land & built with state of the art German
Technology in the idyllic town of Lumshnong, a strategic location at
Meghalaya, a place that ensures easy availability of high-grade limestone.
Star Cement Plant is the largest in North East & one of the most advanced in
India.
<br /><br />
Star Cement has also fast expanding its footprint in West Bengal & Bihar.
With a distribution network with over 6000 plus in North East India and 6000
Plus in Bengal and Bihar, Star Cement produces three grades of cement namely
PPC, PSC and Anti rust Cement known & admired for its high quality, high
strength cement.
